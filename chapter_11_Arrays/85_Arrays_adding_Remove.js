let arr = [1, 2, 3];
console.log(arr);

//Add to End
arr.push(4);
console.log(arr);

//Add multiple elements
arr.push(6, 5);
console.log(arr);

//Remove from End
arr.pop();
console.log(arr);

//Add to Beginning
arr.unshift(0); //1 will add at the Beginning
console.log(arr);

//Remove from Beginning
arr.shift();
console.log(arr);

